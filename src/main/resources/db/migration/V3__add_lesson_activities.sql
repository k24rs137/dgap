CREATE TABLE IF NOT EXISTS lesson_activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    lesson_key VARCHAR(160) NOT NULL,
    pre_correct BOOLEAN,
    post_correct BOOLEAN,
    mission_completed BOOLEAN NOT NULL DEFAULT FALSE,
    review_due_at TIMESTAMP(6) WITH TIME ZONE,
    reviewed_at TIMESTAMP(6) WITH TIME ZONE,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_activity_user_lesson UNIQUE (user_id, lesson_key),
    CONSTRAINT fk_activity_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX IF NOT EXISTS idx_activity_user ON lesson_activities (user_id);
CREATE INDEX IF NOT EXISTS idx_activity_review_due ON lesson_activities (review_due_at);
