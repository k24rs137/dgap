CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(40) NOT NULL UNIQUE,
    password VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS learning_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    lesson_key VARCHAR(160) NOT NULL,
    title VARCHAR(200) NOT NULL,
    completed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_learning_user_lesson UNIQUE (user_id, lesson_key),
    CONSTRAINT fk_learning_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE IF NOT EXISTS favorite_lessons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    lesson_key VARCHAR(160) NOT NULL,
    CONSTRAINT uk_favorite_user_lesson UNIQUE (user_id, lesson_key),
    CONSTRAINT fk_favorite_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE IF NOT EXISTS community_posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    text VARCHAR(1000) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_post_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE IF NOT EXISTS community_likes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    CONSTRAINT uk_like_post_user UNIQUE (post_id, user_id),
    CONSTRAINT fk_like_post FOREIGN KEY (post_id) REFERENCES community_posts (id),
    CONSTRAINT fk_like_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX IF NOT EXISTS idx_progress_user ON learning_progress (user_id);
CREATE INDEX IF NOT EXISTS idx_favorite_user ON favorite_lessons (user_id);
CREATE INDEX IF NOT EXISTS idx_post_created ON community_posts (created_at);
CREATE INDEX IF NOT EXISTS idx_like_post ON community_likes (post_id);
